# מטרה: מספק פונקציות לחילוץ מידע מהתקנים ובניית כללי USBGuard
#
# פונקציות עיקריות:
#   • _parse_device_info - חילוץ שדות ספציפיים משורת התקן (מהיר, ללא subprocess)
#   • _build_rule - בניית כלל allow מלא מהתקן חסום
#
# שיפורי ביצועים (v2.3):
#   • שימוש ב-Bash regex built-in ([[ $var =~ regex ]]) במקום grep -P
#   • Zero external processes - הכל רץ בזיכרון של Bash
#   • מהיר פי 50-100 מגרסאות קודמות
#   • Portable - עובד על כל מערכת Linux, Alpine, macOS
#
# תלותיות:
#   • דורש log_error מ-logger.sh
#   • דורש מערך BLOCKED_DEVICES מוגדר לפני קריאה ל-_build_rule
#
# שימוש:
#   source scripts/lib/device-utils.sh
#   vid=$(_parse_device_info "$device_line" "id")
#   rule=$(_build_rule "5")
# ═══════════════════════════════════════════════════════════════════════════════

# ═══════════════════════════════════════════════════════════════════════════════
# פונקציה: _parse_device_info
# תפקיד: חילוץ מידע ספציפי משורת התקן של USBGuard
#
# פרמטרים:
#   $1 - device_line: שורה מלאה מהפלט של "usbguard list-devices"
#   $2 - field: השדה המבוקש (id, serial, name, hash, port, device_id)
#
# החזרה:
#   stdout: הערך של השדה המבוקש
#   אם השדה לא נמצא - מחזיר ערך ברירת מחדל (תלוי בשדה)
#
# דוגמה לשורת קלט:
#   "0: block id 0781:5581 serial 4C530001010412113934 name "SanDisk Ultra" 
#    hash abc123 parent-hub 1-2 via-port 1-2.3 with-interface { 08:06:50 }"
#
# ביצועים:
#   • Zero external processes (אין echo, אין grep, אין pipe)
#   • שימוש ב-Bash regex built-in: [[ $var =~ regex ]]
#   • תפיסת תוצאה במערך BASH_REMATCH
# ═══════════════════════════════════════════════════════════════════════════════
_parse_device_info() {
    local device_line="$1"  # שורת ההתקן המלאה
    local field="$2"        # השדה המבוקש
    local result=""         # משתנה לאחסון התוצאה

    # ═══════════════════════════════════════════════════════════════════════════
    # שימוש ב-case לבחירת הביטוי הרגולרי המתאים לשדה
    # כל case משתמש ב-[[ $var =~ regex ]] עם BASH_REMATCH
    # ═══════════════════════════════════════════════════════════════════════════
    case "$field" in
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ Vendor:Product ID (פורמט: XXXX:YYYY)
        # דוגמה: "id 0781:5581" → "0781:5581"
        # ═══════════════════════════════════════════════════════════════════════
        id)
            # הסוגריים () ב-Regex תופסים את החלק לתוך BASH_REMATCH[1]
            # [0-9a-fA-F]{4}: בדיוק 4 תווים הקסדצימליים
            # \ : רווח אחרי המילה id
            if [[ $device_line =~ id\ ([0-9a-fA-F]{4}:[0-9a-fA-F]{4}) ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            ;;
        
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ מספר סידורי
        # דוגמה: "serial 4C530001010412113934" → "4C530001010412113934"
        # אם אין serial - מחזיר "no-serial"
        # ═══════════════════════════════════════════════════════════════════════
        serial)
            # \"? : מרכאה אופציונלית (לפעמים יש, לפעמים אין)
            # [^\"\ ]+ : תווים שאינם מרכאה או רווח (ה-serial עצמו)
            if [[ $device_line =~ serial\ \"?([^\"\ ]+) ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            # :- : אם result ריק, השתמש ב-"no-serial"
            result="${result:-no-serial}"
            ;;
        
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ שם ההתקן
        # דוגמה: 'name "SanDisk Ultra"' → "SanDisk Ultra"
        # אם אין שם - מחזיר "Unknown Device"
        # ═══════════════════════════════════════════════════════════════════════
        name)
            # \" : מרכאה פותחת
            # [^\"]+ : תווים שאינם מרכאה (השם עצמו)
            # \" : מרכאה סוגרת
            if [[ $device_line =~ name\ \"([^\"]+)\" ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            result="${result:-Unknown Device}"
            ;;
        
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ hash ההתקן (טביעת אצבע קריפטוגרפית)
        # דוגמה: "hash abc123" → "abc123"
        # ═══════════════════════════════════════════════════════════════════════
        hash)
            # \"? : מרכאה אופציונלית
            # [^\"\ ]+ : תווים שאינם מרכאה או רווח (ה-hash עצמו)
            if [[ $device_line =~ hash\ \"?([^\"\ ]+) ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            ;;
        
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ port דרכו ההתקן מחובר
        # דוגמה: "via-port 1-2.3" → "1-2.3"
        # אם אין port - מחזיר "N/A"
        # ═══════════════════════════════════════════════════════════════════════
        port)
            # \"? : מרכאה אופציונלית
            # [^\"\ ]+ : תווים שאינם מרכאה או רווח (ה-port עצמו)
            if [[ $device_line =~ via-port\ \"?([^\"\ ]+) ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            result="${result:-N/A}"
            ;;
        
        # ═══════════════════════════════════════════════════════════════════════
        # חילוץ device_id (מספר סידורי של ההתקן ברשימה)
        # דוגמה: "5: block id ..." → "5"
        # זהו המספר לפני ה-: בהתחלה
        # ═══════════════════════════════════════════════════════════════════════
        device_id)
            # ^ : תחילת שורה
            # ([0-9]+): ספרות (ה-device_id)
            # : : נקודתיים אחרי המספר
            if [[ $device_line =~ ^([0-9]+): ]]; then
                result="${BASH_REMATCH[1]}"
            fi
            ;;
    esac

    # ═══════════════════════════════════════════════════════════════════════════
    # החזרת התוצאה ל-stdout
    # המשתמש יכול ללכוד את הפלט עם: var=$(_parse_device_info ...)
    # ═══════════════════════════════════════════════════════════════════════════
    echo "$result"
}

# ═══════════════════════════════════════════════════════════════════════════════
# פונקציה: _build_rule
# תפקיד: בניית כלל allow מלא מהתקן חסום
#
# פרמטרים:
#   $1 - device_id: המספר הסידורי של ההתקן (לא ה-Vendor:Product)
#
# החזרה:
#   stdout: שורת כלל USBGuard מלאה
#   return code: 0 אם הצליח, 1 אם נכשל
#
# דוגמה לפלט:
#   "allow id 0781:5581 serial "4C530001010412113934" name "SanDisk Ultra" 
#    hash "abc123" with-interface { 08:06:50 }"
#
# תלותיות:
#   • דורש מערך BLOCKED_DEVICES מוגדר (מכיל רשימת התקנים חסומים)
#   • דורש log_error מ-logger.sh
# ═══════════════════════════════════════════════════════════════════════════════
_build_rule() {
    local device_id="$1"
    local device_line=""

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 1: מציאת שורת ההתקן המלאה לפי device_id
    # עובר על כל ההתקנים במערך BLOCKED_DEVICES ומחפש התאמה
    # ═══════════════════════════════════════════════════════════════════════════
    for d in "${BLOCKED_DEVICES[@]}"; do
        local did
        # חילוץ ה-device_id מהשורה הנוכחית (מהיר - ללא subprocess)
        did=$(_parse_device_info "$d" "device_id")
        if [[ "$did" == "$device_id" ]]; then
            # נמצאה התאמה - שומר את השורה המלאה ויוצא מהלולאה
            device_line="$d"
            break
        fi
    done

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 2: וידוא שההתקן נמצא
    # אם לא נמצא - רושם שגיאה וחוזר עם קוד 1
    # ═══════════════════════════════════════════════════════════════════════════
    if [[ -z "$device_line" ]]; then
        log_error "APPROVE" "Device ID ${device_id} not found in blocked list"
        return 1
    fi

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 3: חילוץ כל השדות הנדרשים מהשורה המלאה
    # כל שדה מחולץ בנפרד באמצעות _parse_device_info (מהיר מאוד)
    # ═══════════════════════════════════════════════════════════════════════════
    local vid_pid serial name hash_val interfaces
    
    # Vendor:Product ID - חובה (בלעדיו אי אפשר לבנות כלל)
    vid_pid=$(_parse_device_info "$device_line" "id")
    
    # מספר סידורי - אופציונלי (מוסיף זיהוי נוסף)
    serial=$(_parse_device_info "$device_line" "serial")
    
    # שם ההתקן - אופציונלי (לקריאות בלבד)
    name=$(_parse_device_info "$device_line" "name")
    
    # Hash - אופציונלי (טביעת אצבע קריפטוגרפית - חזק יותר)
    hash_val=$(_parse_device_info "$device_line" "hash")
    
    # ═══════════════════════════════════════════════════════════════════════════
    # חילוץ interfaces - תומך בשני פורמטים:
    # 1. פורמט מרובה: "with-interface { 08:06:50 03:00:00 }"
    # 2. פורמט בודד: "with-interface 08:06:50"
    # ═══════════════════════════════════════════════════════════════════════════
    
    # ניסיון ראשון: פורמט עם סוגריים (multi-interface)
    # שימוש ב-Bash regex - מהיר יותר מ-grep
    if [[ $device_line =~ with-interface\ \{([^\}]+)\} ]]; then
        interfaces="{${BASH_REMATCH[1]}}"
    # אם לא נמצא - ניסיון שני: פורמט בודד
    elif [[ $device_line =~ with-interface\ ([^\ ]+) ]]; then
        interfaces="${BASH_REMATCH[1]}"
    else
        interfaces=""
    fi

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 4: וידוא שיש לפחות Vendor:Product ID
    # זהו השדה המינימלי הנדרש לבניית כלל תקין
    # ═══════════════════════════════════════════════════════════════════════════
    if [[ -z "$vid_pid" ]]; then
        log_error "APPROVE" "Cannot extract vendor:product ID for device ${device_id}"
        return 1
    fi

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 5: בניית הכלל בצורה הדרגתית
    # מתחיל עם השדה החובה (id) ומוסיף שדות אופציונליים רק אם קיימים
    # ═══════════════════════════════════════════════════════════════════════════
    
    # שורה בסיסית - חובה
    local rule="allow id ${vid_pid}"
    
    # הוספת serial - רק אם קיים ולא "no-serial"
    [[ "$serial" != "no-serial" && -n "$serial" ]] && rule+=" serial \"${serial}\""
    
    # הוספת name - רק אם קיים ולא "Unknown Device"
    [[ -n "$name" && "$name" != "Unknown Device" ]] && rule+=" name \"${name}\""
    
    # הוספת hash - רק אם קיים (מחזק את הזיהוי)
    [[ -n "$hash_val" ]] && rule+=" hash \"${hash_val}\""
    
    # הוספת interfaces - רק אם קיים
    [[ -n "$interfaces" ]] && rule+=" with-interface ${interfaces}"

    # ═══════════════════════════════════════════════════════════════════════════
    # שלב 6: החזרת הכלל המלא
    # הכלל מודפס ל-stdout ויכול להילכד ע"י המשתמש
    # ═══════════════════════════════════════════════════════════════════════════
    echo "$rule"
}
